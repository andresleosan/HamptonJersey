-- PUB-10: requests from the public «Sell or let» form (site/owner.js, server/owner-requests.js). Received only with
-- OWNER_REQUESTS_READY=1 and an app_settings row owner_enquiries = {"enabled":true,"privacy_version":"<published notice>"};
-- this migration installs neither, so intake stays closed. Only Luis opens it.
-- Additive: two new tables, one index and three triggers; no existing row or table changes. Events and notifications
-- keep their CHECKs: the event is a 'collection' entity 'owner-request:<id>' (the backups:* precedent) and the task has
-- no target_kind, with task_key 'owner-request:<id>'. Neither carries personal data.

-- request_id: generated by the form, so a retried submission returns the same answer. payload_hash: SHA-256 of the
-- normalised fields, never shown. status changes only by a person's explicit action in the panel.
CREATE TABLE owner_requests (
  id TEXT PRIMARY KEY, request_id TEXT NOT NULL UNIQUE, payload_hash TEXT NOT NULL,
  name TEXT NOT NULL, phone TEXT NOT NULL, email TEXT NOT NULL, address TEXT NOT NULL,
  operation TEXT NOT NULL CHECK (operation IN ('sale','rent')),
  valuation_requested INTEGER NOT NULL CHECK (valuation_requested IN (0,1)),
  privacy_version TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new','contacted','closed')),
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE INDEX owner_requests_status ON owner_requests (status, created_at, id);

-- One receipt per form request ID; erasing the request erases its receipt.
CREATE TABLE owner_request_receipts (
  request_id TEXT PRIMARY KEY,
  owner_request_id TEXT NOT NULL UNIQUE REFERENCES owner_requests(id) ON DELETE CASCADE,
  payload_hash TEXT NOT NULL, created_at TEXT NOT NULL
);

-- Re-checks the switch row and the notice version in the same statement, after the anti-spam check.
CREATE TRIGGER owner_requests_policy BEFORE INSERT ON owner_requests BEGIN
  SELECT RAISE(ABORT, 'owner requests unavailable') WHERE NOT EXISTS (SELECT 1 FROM app_settings
    WHERE key = 'owner_enquiries' AND json_extract(value, '$.enabled') = 1
      AND json_extract(value, '$.privacy_version') = NEW.privacy_version
      AND length(json_extract(value, '$.privacy_version')) BETWEEN 1 AND 120);
END;

-- Receipt, event (operation and valuation flag only) and the team's Inbox task, in the insert's own transaction.
CREATE TRIGGER owner_requests_created AFTER INSERT ON owner_requests BEGIN
  INSERT INTO owner_request_receipts (request_id, owner_request_id, payload_hash, created_at)
    VALUES (NEW.request_id, NEW.id, NEW.payload_hash, NEW.created_at);
  INSERT INTO events (at, actor, entity_type, entity_id, type, data)
    VALUES (NEW.created_at, 'public', 'collection', 'owner-request:' || NEW.id, 'owner.requested',
      json_object('operation', NEW.operation, 'valuation_requested', NEW.valuation_requested));
  INSERT INTO notifications (event_id, category, title, action_required, created_at, task_key)
    SELECT id, 'task', CASE WHEN NEW.valuation_requested = 1 THEN 'Contact property owner · valuation requested'
      ELSE 'Contact property owner' END, 1, NEW.created_at, 'owner-request:' || NEW.id
    FROM events WHERE entity_type = 'collection' AND entity_id = 'owner-request:' || NEW.id AND type = 'owner.requested';
END;

-- Erasure: the task stays as history, closed and without a link.
CREATE TRIGGER owner_requests_erased AFTER DELETE ON owner_requests BEGIN
  UPDATE notifications SET title = 'Deleted owner request', task_reason = NULL, target_deleted = 1,
    resolved_at = COALESCE(resolved_at, strftime('%Y-%m-%dT%H:%M:%fZ', 'now')), resolved_by = COALESCE(resolved_by, 'system'),
    closed_by_source = 1
    WHERE task_key = 'owner-request:' || OLD.id;
END;
