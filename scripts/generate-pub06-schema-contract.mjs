// Generate the runtime identity check from the canonical combined migration.
// This never applies SQL. Run with --check to detect drift.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { unstable_splitSqlQuery } = require('wrangler');
const source = new URL('../migrations/0052_listing_economics_history.sql', import.meta.url);
const output = new URL('../server/listing-economics-contract.js', import.meta.url);
const names = ['listing_event_insert', 'listing_event_update', 'pub06_costs_guard_insert', 'pub06_costs_guard_update'];
const entries = new Map();
for (const statement of unstable_splitSqlQuery(readFileSync(source, 'utf8'))) {
  const match = /\bCREATE\s+TRIGGER\s+([a-z_][a-z_0-9]*)\b/i.exec(statement);
  if (!match || !names.includes(match[1])) continue;
  if (entries.has(match[1])) throw new Error('Duplicate PUB-06 trigger');
  entries.set(match[1], statement.slice(match.index).trim().replace(/;$/, ''));
}
if (names.some(name => !entries.has(name))) throw new Error('Missing PUB-06 trigger');
const contents = '// Generated by scripts/generate-pub06-schema-contract.mjs; do not edit by hand.\n' +
  'export const PUB06_TRIGGER_SQL = Object.freeze(' + JSON.stringify(Object.fromEntries(names.map(name => [name, entries.get(name)])), null, 2) + ');\n';
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== contents) throw new Error('PUB-06 schema contract is stale');
} else writeFileSync(output, contents);
